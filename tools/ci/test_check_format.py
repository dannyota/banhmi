"""Hosted formatting regressions in disposable Git repositories."""
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / 'tools/ci/check_format.sh'
DIRTY = 'package fixture\n\nfunc Value( ) int {return 1}\n'


class FormatContractTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / 'repository'
        self.root.mkdir()
        self.env = {**os.environ, 'GOTOOLCHAIN': 'local', 'GIT_CONFIG_GLOBAL': '/dev/null',
                    'GIT_CONFIG_NOSYSTEM': '1'}
        self.version = subprocess.check_output(
            ['go', 'env', 'GOVERSION'], cwd=self.root,
            env=self.env, text=True).strip().removeprefix('go')
        self.goroot = subprocess.check_output(
            ['go', 'env', 'GOROOT'], cwd=self.root, env=self.env, text=True).strip()
        self.git('init', '-b', 'master')
        (self.root / 'go.mod').write_text(f'module fixture\n\ngo {self.version}\n')

    def git(self, *args):
        return subprocess.run(['git', *args], cwd=self.root, env=self.env,
                              capture_output=True, check=True)

    def tracked(self, relative, contents=DIRTY):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
        self.git('add', '--', relative)
        return path

    def run_script(self, *args):
        return subprocess.run(['bash', str(SCRIPT), *args], cwd=self.root, env=self.env,
                              capture_output=True, text=True)

    def test_check_artifact_write_and_exact_file_set(self):
        names = ['normal.go', 'space name.go', 'line\nbreak.go', '-flag.go',
                 '.hidden/fixture.go', 'pkg/store/auth/generated.go', 'tagged.go',
                 'tracked-ignored.go']
        for name in names:
            prefix = ('//go:build unavailable\n\n' if name == 'tagged.go' else
                      '// Code generated by sqlc. DO NOT EDIT.\n' if 'generated' in name else '')
            self.tracked(name, prefix + DIRTY)
        self.tracked('notes.txt', 'untouched\n')
        (self.root / 'untracked.go').write_text(DIRTY)
        (self.root / '.gitignore').write_text('ignored.go\ntracked-ignored.go\n')
        (self.root / 'ignored.go').write_text(DIRTY)
        before = {name: (self.root / name).read_bytes() for name in names}
        artifact = Path(self.temporary.name) / 'artifact'
        result = self.run_script('--check', '--artifact-dir', str(artifact))
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn('normal.go', result.stderr)
        self.assertEqual({p.relative_to(artifact / 'files').as_posix()
                          for p in (artifact / 'files').rglob('*.go')}, set(names))
        self.assertIn(self.version, (artifact / 'result.txt').read_text())
        for name in names:
            self.assertEqual((self.root / name).read_bytes(), before[name])
            formatted = subprocess.check_output(
                [f'{self.goroot}/bin/gofmt', str(self.root / name)])
            self.assertEqual((artifact / 'files' / name).read_bytes(), formatted)
        self.assertEqual(self.run_script('--write').returncode, 0)
        self.assertEqual(self.run_script().returncode, 0)
        for name in names:
            self.assertEqual((self.root / name).read_bytes(),
                             (artifact / 'files' / name).read_bytes())
        for name in ('untracked.go', 'ignored.go'):
            self.assertEqual((self.root / name).read_text(), DIRTY)
        self.git('diff', '-w', '--exit-code', '--', '*.go')
        # The script never stages its working-tree repairs.
        self.assertEqual(self.git('show', ':normal.go').stdout.decode(), DIRTY)

    def test_empty_set_and_invalid_arguments(self):
        self.assertEqual(self.run_script().returncode, 0)
        for args in [('--unknown',), ('--write', '--artifact-dir', 'output'),
                     ('--check', '--artifact-dir', ''), ('--check', 'extra')]:
            with self.subTest(args=args):
                self.assertNotEqual(self.run_script(*args).returncode, 0)

    def test_syntax_errors_deleted_files_and_symlinks_fail(self):
        path = self.tracked('bad.go', 'package fixture\nfunc broken(\n')
        self.assertNotEqual(self.run_script().returncode, 0)
        self.assertNotEqual(self.run_script('--write').returncode, 0)
        path.unlink()
        self.assertNotEqual(self.run_script().returncode, 0)
        path.symlink_to('untracked.go')
        (self.root / 'untracked.go').write_text(DIRTY)
        self.assertNotEqual(self.run_script().returncode, 0)
        self.assertEqual((self.root / 'untracked.go').read_text(), DIRTY)

    def test_wrong_toolchain_and_stale_artifact_fail(self):
        (self.root / 'go.mod').write_text('module fixture\n\ngo 1.0.0\n')
        result = self.run_script()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('need Go 1.0.0', result.stderr)
        self.assertNotEqual(self.run_script('--write').returncode, 0)
        (self.root / 'go.mod').write_text('module fixture\n\ngo 1.26\n')
        self.assertNotEqual(self.run_script().returncode, 0)
        self.assertNotEqual(self.run_script('--check', '--artifact-dir', str(self.root)).returncode, 0)

    def test_tool_and_git_errors_propagate(self):
        self.tracked('normal.go')
        binaries = Path(self.temporary.name) / 'bin'
        binaries.mkdir()
        real_git = shutil.which('git')
        real_go = shutil.which('go')
        self.env['PATH'] = str(binaries) + os.pathsep + self.env['PATH']
        fake_git = binaries / 'git'
        fake_git.write_text('#!/usr/bin/env bash\n'
                            'if [[ "$1" == ls-files ]]; then exit 23; fi\n'
                            f'exec "{real_git}" "$@"\n')
        fake_git.chmod(0o755)
        self.assertEqual(self.run_script().returncode, 23)
        fake_git.unlink()
        fake_root = Path(self.temporary.name) / 'toolchain'
        (fake_root / 'bin').mkdir(parents=True)
        fake_go = binaries / 'go'
        fake_go.write_text('#!/usr/bin/env bash\n'
                           f'if [[ "$2" == GOROOT ]]; then echo "{fake_root}"; exit; fi\n'
                           f'exec "{real_go}" "$@"\n')
        fake_go.chmod(0o755)
        self.assertNotEqual(self.run_script().returncode, 0)  # No PATH gofmt fallback.
        formatter = fake_root / 'bin/gofmt'
        formatter.write_text('#!/usr/bin/env bash\nexit 24\n')
        formatter.chmod(0o755)
        for mode in ('--check', '--write'):
            self.assertEqual(self.run_script(mode).returncode, 24)
        formatter.write_text('#!/usr/bin/env bash\n'
                             'if [[ "$1" == -l ]]; then echo "$2"; exit; fi\nexit 25\n')
        artifact = Path(self.temporary.name) / 'artifact'
        self.assertEqual(self.run_script('--check', '--artifact-dir', str(artifact)).returncode, 25)
        self.assertIn('did not complete', (artifact / 'result.txt').read_text())
