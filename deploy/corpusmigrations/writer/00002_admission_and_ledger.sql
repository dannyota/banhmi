-- Epoch rotation is the only permitted admission update. Recovery must choose
-- an epoch above the external recovery watermark as well as this stored epoch.
-- +goose StatementBegin
CREATE FUNCTION ingest.check_admission_rotation() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $rotation$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'admission cannot be deleted' USING ERRCODE = '55000';
    END IF;
    IF NEW.id <> OLD.id OR NEW.country_code <> OLD.country_code
       OR NEW.admission_epoch <= OLD.admission_epoch THEN
        RAISE EXCEPTION 'admission rotation requires a greater epoch' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$rotation$;
-- +goose StatementEnd
CREATE TRIGGER country_admission_rotation BEFORE UPDATE OR DELETE ON ingest.country_admission
    FOR EACH ROW EXECUTE FUNCTION ingest.check_admission_rotation();

