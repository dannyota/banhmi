CREATE FUNCTION ingest.check_document_admission_limit() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $limit$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'admission limits cannot be deleted' USING ERRCODE = '55000';
    END IF;
    IF NEW.id = OLD.id AND NEW.next_queue = OLD.next_queue
        AND NEW.revision = OLD.revision + 1 THEN
        RETURN NEW;
    END IF;
    IF NEW.next_queue IS DISTINCT FROM OLD.next_queue AND
        (to_jsonb(NEW) - 'next_queue') = (to_jsonb(OLD) - 'next_queue') THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'invalid admission configuration or queue update' USING ERRCODE = '55000';
END
$limit$;
-- +goose StatementEnd
CREATE TRIGGER document_admission_limit_frozen BEFORE UPDATE OR DELETE ON ingest.document_admission_limit FOR EACH ROW EXECUTE FUNCTION ingest.check_document_admission_limit();

-- +goose StatementBegin
CREATE FUNCTION ingest.check_document_admission_slot() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $slot$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'admission slots cannot be deleted' USING ERRCODE = '55000';
    END IF;
    IF OLD.state = 'released' OR NEW.revision <> OLD.revision + 1
        OR NEW.settled_watermark < OLD.settled_watermark OR
        (to_jsonb(NEW) - ARRAY['current_execution_id', 'admission_epoch', 'lease_owner',
            'attempt_fence', 'revision', 'settled_watermark', 'state', 'wait_reason',
            'resume_requested_at', 'terminal_reason', 'terminal_result_id', 'updated_at']) <>
        (to_jsonb(OLD) - ARRAY['current_execution_id', 'admission_epoch', 'lease_owner',
            'attempt_fence', 'revision', 'settled_watermark', 'state', 'wait_reason',
            'resume_requested_at', 'terminal_reason', 'terminal_result_id', 'updated_at']) THEN
        RAISE EXCEPTION 'invalid admission slot update' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END
$slot$;
-- +goose StatementEnd
CREATE TRIGGER document_admission_slot_frozen BEFORE UPDATE OR DELETE ON ingest.document_admission_slot FOR EACH ROW EXECUTE FUNCTION ingest.check_document_admission_slot();

