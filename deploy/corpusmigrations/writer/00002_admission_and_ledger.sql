CREATE TABLE ingest.execution_result (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_key text NOT NULL UNIQUE CHECK (result_key ~ '^result-[0-9a-f]{32}$'),
    execution_id bigint NOT NULL REFERENCES ingest.execution (id),
    stage text NOT NULL CHECK (stage IN ('discover', 'fetch', 'extract', 'ocr', 'normalize', 'index', 'dense', 'lexical', 'evaluate', 'publish', 'activate')),
    substep text NOT NULL CHECK (substep <> ''),
    shard text NOT NULL CHECK (shard <> ''),
    idempotency_key text NOT NULL UNIQUE CHECK (idempotency_key ~ '^sha256:[0-9a-f]{64}$'),
    input_digest text NOT NULL CHECK (input_digest ~ '^[0-9a-f]{64}$'),
    output_digest text NOT NULL CHECK (output_digest ~ '^[0-9a-f]{64}$'),
    recipe_digest text NOT NULL CHECK (recipe_digest ~ '^[0-9a-f]{64}$'),
    budget_digest text NOT NULL CHECK (budget_digest ~ '^[0-9a-f]{64}$'),
    decision_revision bigint NOT NULL CHECK (decision_revision >= 0),
    outcome text NOT NULL CHECK (outcome IN ('succeeded', 'pending_retry', 'terminal_gap', 'rejected', 'failed')),
    expected bigint NOT NULL CHECK (expected >= 0),
    processed bigint NOT NULL CHECK (processed >= 0 AND processed <= expected),
    succeeded bigint NOT NULL CHECK (succeeded >= 0),
    pending_retry bigint NOT NULL CHECK (pending_retry >= 0),
    terminal_gap bigint NOT NULL CHECK (terminal_gap >= 0),
    rejected bigint NOT NULL CHECK (rejected >= 0),
    failed bigint NOT NULL CHECK (failed >= 0),
    accepted_gaps bigint NOT NULL CHECK (accepted_gaps >= 0 AND accepted_gaps <= terminal_gap),
    cursor text NOT NULL,
    next_eligible_at timestamptz,
    gap_acceptance_ref text,
    complete boolean NOT NULL,
    payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (processed::numeric = succeeded::numeric + pending_retry + terminal_gap + rejected + failed),
    CHECK ((pending_retry > 0) = (next_eligible_at IS NOT NULL)),
    CHECK ((accepted_gaps > 0) = (gap_acceptance_ref IS NOT NULL)),
    CHECK (NOT complete OR (processed = expected AND pending_retry = 0 AND rejected = 0 AND failed = 0 AND terminal_gap = accepted_gaps))
);
