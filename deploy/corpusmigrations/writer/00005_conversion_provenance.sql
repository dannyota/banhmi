-- Same-schema parent binding also protects direct runtime inserts. Cross-schema
-- existence, sizes and lease ownership are checked by the fenced queries.
-- +goose StatementBegin
CREATE FUNCTION silver.check_conversion_parent() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $guard$
BEGIN
    IF NEW.document_revision_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM silver.document_revision r WHERE r.id = NEW.document_revision_id
          AND r.revision_key = NEW.revision_key AND r.document_version_key = NEW.document_version_key
    ) THEN
        RAISE EXCEPTION 'provenance differs from document revision' USING ERRCODE = '23514';
    END IF;
    IF TG_TABLE_NAME = 'quality_finding' THEN
        IF NOT EXISTS (SELECT 1 FROM silver.quality_report q WHERE q.id = NEW.quality_report_id
            AND NEW.ordinal < q.record_count
            AND ROW(q.document_revision_id, q.revision_key, q.document_version_key,
                    q.processing_execution_key, q.candidate_digest, q.report_hash)
                IS NOT DISTINCT FROM ROW(NEW.document_revision_id, NEW.revision_key, NEW.document_version_key,
                    NEW.processing_execution_key, NEW.candidate_digest, NEW.report_hash)) THEN
            RAISE EXCEPTION 'finding differs from report' USING ERRCODE = '23514';
        END IF;
    ELSIF TG_TABLE_NAME = 'revision_comparison' THEN
        IF NOT EXISTS (SELECT 1 FROM silver.quality_report p JOIN silver.quality_report q
            ON q.id = NEW.candidate_report_id WHERE p.id = NEW.prior_report_id
            AND p.revision_key = NEW.prior_revision_key AND p.candidate_digest = NEW.prior_candidate_digest
            AND ROW(q.revision_key, q.document_version_key, q.candidate_digest)
                IS NOT DISTINCT FROM ROW(NEW.revision_key, NEW.document_version_key, NEW.candidate_digest)
            AND (q.document_revision_id IS NULL OR q.document_revision_id = NEW.document_revision_id)
            AND split_part(p.revision_key, ':rev:', 1) = split_part(q.revision_key, ':rev:', 1)) THEN
            RAISE EXCEPTION 'comparison differs from candidates' USING ERRCODE = '23514';
        END IF;
        IF NEW.acceptance_watermark <> COALESCE((SELECT max(a.watermark)
            FROM ingest.revision_acceptance a
            WHERE split_part(a.revision_key, ':rev:', 1) = split_part(NEW.revision_key, ':rev:', 1)
              AND a.state IN ('accepted', 'accepted_with_gaps')), 0) THEN
            RAISE EXCEPTION 'comparison watermark differs from acceptance history' USING ERRCODE = '23514';
        END IF;
        IF NEW.stale THEN
            RAISE EXCEPTION 'new comparison cannot be stale' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END
$guard$;
