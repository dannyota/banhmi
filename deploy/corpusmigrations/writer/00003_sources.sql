CREATE TABLE ingest.artifact_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key text NOT NULL UNIQUE CHECK (request_key ~ '^request-[0-9a-f]{32}$'),
    source_window_id bigint NOT NULL REFERENCES ingest.source_window (id),
    source_rate_limit_id bigint NOT NULL REFERENCES ingest.source_rate_limit (id),
    document_version_key text NOT NULL CHECK (document_version_key ~ '^[a-z0-9][a-z0-9_.-]{0,127}$'),
    owner_kind text NOT NULL CHECK (owner_kind = 'observation'),
    owner_key text NOT NULL CHECK (owner_key ~ '^observation-[0-9a-f]{32}$'),
    purpose text NOT NULL CHECK (purpose IN ('detail', 'artifact')),
    expected_role text CHECK (expected_role IN ('main', 'appendix', 'original_scan')),
    expected_response_kind text NOT NULL CHECK (expected_response_kind IN ('', 'metadata', 'files', 'tree', 'diagram')),
    required boolean NOT NULL,
    request_plan jsonb NOT NULL CHECK (jsonb_typeof(request_plan) = 'object'),
    request_cursor text NOT NULL,
    source_attempt_limit integer NOT NULL CHECK (source_attempt_limit BETWEEN 1 AND 5),
    retry_started_at timestamptz NOT NULL,
    retry_deadline_at timestamptz NOT NULL CHECK (retry_deadline_at > retry_started_at AND retry_deadline_at <= retry_started_at + interval '24 hours'),
    source_attempts integer NOT NULL DEFAULT 0 CHECK (source_attempts BETWEEN 0 AND source_attempt_limit),
    infrastructure_attempts integer NOT NULL DEFAULT 1 CHECK (infrastructure_attempts BETWEEN 1 AND 3),
    next_eligible_at timestamptz,
    -- The trigger retains the greatest due time through leased and terminal states.
    eligibility_watermark timestamptz,
    retry_after timestamptz,
    last_attempt_key text CHECK (last_attempt_key ~ '^request-[0-9a-f]{32}$'),
    claimed_epoch bigint CHECK (claimed_epoch > 0),
    claimed_fence bigint CHECK (claimed_fence > 0),
    state text NOT NULL CHECK (state IN ('due', 'leased', 'fetched', 'verified', 'failed', 'exhausted', 'expired')),
    reason text,
    capture_key text CHECK (capture_key ~ '^capture-[0-9a-f]{32}$'),
    capture_digest text CHECK (capture_digest ~ '^[0-9a-f]{64}$'),
    capture_bytes bigint CHECK (capture_bytes >= 0),
    transport_receipt jsonb CHECK (jsonb_typeof(transport_receipt) = 'object'),
    CHECK ((purpose = 'artifact') = (expected_role IS NOT NULL)),
    CHECK (purpose = 'detail' OR expected_response_kind = ''),
    CHECK ((state = 'due') = (next_eligible_at IS NOT NULL)),
    CHECK (next_eligible_at IS NULL OR (eligibility_watermark IS NOT NULL AND next_eligible_at >= eligibility_watermark)),
    CHECK (next_eligible_at IS NULL OR retry_after IS NULL OR next_eligible_at >= retry_after),
    CHECK (num_nonnulls(capture_key, capture_digest, capture_bytes, transport_receipt) IN (0, 4)),
    CHECK (state NOT IN ('fetched', 'verified') OR capture_key IS NOT NULL),
    CHECK (state NOT IN ('due', 'leased', 'exhausted') OR capture_key IS NULL),
    CHECK ((state IN ('failed', 'exhausted', 'expired')) = (reason IS NOT NULL)),
    CHECK (reason IS NULL OR reason <> ''),
    CHECK (state <> 'leased' OR (claimed_epoch IS NOT NULL AND claimed_fence IS NOT NULL))
);
