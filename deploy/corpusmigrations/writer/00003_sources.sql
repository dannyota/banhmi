CREATE TABLE ingest.source_window (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_key text NOT NULL UNIQUE CHECK (window_key ~ '^[a-z0-9][a-z0-9_.-]{0,127}$'),
    source_id text NOT NULL CHECK (source_id ~ '^[a-z0-9][a-z0-9_.-]{0,127}$'),
    slice_key text NOT NULL CHECK (slice_key <> ''),
    mode text NOT NULL CHECK (mode IN ('incremental', 'full_sweep', 'backfill')),
    starts_at timestamptz NOT NULL,
    cutoff_at timestamptz NOT NULL CHECK (cutoff_at > starts_at),
    deadline_at timestamptz NOT NULL,
    policy_digest text NOT NULL CHECK (policy_digest ~ '^[0-9a-f]{64}$'),
    budget_digest text NOT NULL CHECK (budget_digest ~ '^[0-9a-f]{64}$'),
    budget jsonb NOT NULL CHECK (jsonb_typeof(budget) = 'object'),
    page_budget integer NOT NULL CHECK (page_budget > 0),
    request_budget integer NOT NULL CHECK (request_budget > 0),
    source_attempt_limit integer NOT NULL CHECK (source_attempt_limit BETWEEN 1 AND 5),
    source_retry_interval interval NOT NULL CHECK (source_retry_interval > interval '0' AND source_retry_interval <= interval '24 hours'),
    initial_cursor text NOT NULL,
    committed_cursor text NOT NULL,
    state text NOT NULL CHECK (state IN ('frozen', 'progressing', 'complete', 'incomplete', 'failed')),
    reason text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((state IN ('incomplete', 'failed')) = (reason IS NOT NULL)),
    CHECK (reason IS NULL OR reason <> ''),
    CHECK (state = 'complete' OR committed_cursor = initial_cursor)
);
CREATE INDEX source_window_progress_idx ON ingest.source_window (source_id, state, id);
CREATE INDEX source_window_policy_idx ON ingest.source_window (policy_digest, id);
CREATE INDEX source_window_budget_idx ON ingest.source_window (budget_digest, id);

CREATE TABLE ingest.discovery_page (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_window_id bigint NOT NULL REFERENCES ingest.source_window (id),
    page_key text NOT NULL CHECK (page_key ~ '^page-[0-9a-f]{32}$'),
    ordinal integer NOT NULL CHECK (ordinal >= 0),
    purpose text NOT NULL CHECK (purpose IN ('listing', 'number')),
    request_cursor text NOT NULL,
    request_plan jsonb NOT NULL CHECK (jsonb_typeof(request_plan) = 'object'),
    state text NOT NULL CHECK (state IN ('requested', 'captured', 'decoded', 'accepted', 'failed')),
    reason text,
    source_attempt_limit integer NOT NULL CHECK (source_attempt_limit BETWEEN 1 AND 5),
    retry_started_at timestamptz NOT NULL,
    retry_deadline_at timestamptz NOT NULL CHECK (retry_deadline_at > retry_started_at AND retry_deadline_at <= retry_started_at + interval '24 hours'),
    source_attempts integer NOT NULL DEFAULT 0 CHECK (source_attempts BETWEEN 0 AND source_attempt_limit),
    infrastructure_attempts integer NOT NULL DEFAULT 1 CHECK (infrastructure_attempts BETWEEN 1 AND 3),
    claim_ordinal integer NOT NULL DEFAULT 0 CHECK (claim_ordinal >= 0),
    claim_state text CHECK (claim_state IN ('issued', 'settled', 'released')),
    CHECK ((claim_ordinal = 0) = (claim_state IS NULL)),
    CHECK (state = 'requested' OR claim_state IS DISTINCT FROM 'issued'),
    retry_after timestamptz,
    last_attempt_key text CHECK (last_attempt_key ~ '^request-[0-9a-f]{32}$'),
    capture_key text CHECK (capture_key ~ '^capture-[0-9a-f]{32}$'),
    capture_digest text CHECK (capture_digest ~ '^[0-9a-f]{64}$'),
    capture_bytes bigint CHECK (capture_bytes >= 0),
    transport_receipt jsonb CHECK (jsonb_typeof(transport_receipt) = 'object'),
    decoded_digest text CHECK (decoded_digest ~ '^[0-9a-f]{64}$'),
    cursor_initial text,
    cursor_committed text,
    cursor_next text,
    cursor_ordinal integer CHECK (cursor_ordinal >= 0),
    complete boolean,
    findings jsonb CHECK (jsonb_typeof(findings) = 'array'),
    acceptance_result_id bigint REFERENCES ingest.execution_result (id),
    UNIQUE (source_window_id, page_key),
    UNIQUE (source_window_id, ordinal),
    CHECK (num_nonnulls(capture_key, capture_digest, capture_bytes, transport_receipt) IN (0, 4)),
    CHECK (num_nonnulls(decoded_digest, cursor_initial, cursor_committed, cursor_next, cursor_ordinal, complete, findings) IN (0, 7)),
    CHECK (decoded_digest IS NULL OR capture_key IS NOT NULL),
    CHECK (complete IS DISTINCT FROM false OR cursor_next = cursor_committed),
    CHECK (state <> 'requested' OR (capture_key IS NULL AND decoded_digest IS NULL)),
    CHECK (state <> 'captured' OR (capture_key IS NOT NULL AND decoded_digest IS NULL)),
    CHECK (state NOT IN ('decoded', 'accepted') OR (capture_key IS NOT NULL AND decoded_digest IS NOT NULL)),
    CHECK ((state = 'accepted') = (acceptance_result_id IS NOT NULL)),
    CHECK ((state = 'failed') = (reason IS NOT NULL)),
    CHECK (reason IS NULL OR reason <> '')
);
-- The ordinal UNIQUE also supplies the required window/order access path.
CREATE INDEX discovery_page_result_idx ON ingest.discovery_page (acceptance_result_id, id);
CREATE INDEX discovery_page_capture_idx ON ingest.discovery_page (capture_digest, id);
CREATE INDEX discovery_page_decoded_idx ON ingest.discovery_page (decoded_digest, id);

