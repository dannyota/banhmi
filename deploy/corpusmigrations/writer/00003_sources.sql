-- Only accounting outcome fields may change. All input allowances stay frozen.
-- +goose StatementBegin
CREATE FUNCTION ingest.check_source_window_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $window$
BEGIN
    IF (to_jsonb(NEW) - ARRAY['committed_cursor', 'state', 'reason']) IS DISTINCT FROM
       (to_jsonb(OLD) - ARRAY['committed_cursor', 'state', 'reason']) THEN
        RAISE EXCEPTION 'source window inputs are frozen' USING ERRCODE = '55000';
    END IF;
    IF OLD.state IN ('complete', 'failed') AND NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'terminal source window cannot change' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END
$window$;
CREATE FUNCTION ingest.check_source_request_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $request$
DECLARE
    mutable_columns text[];
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.eligibility_watermark := GREATEST(NEW.eligibility_watermark, NEW.next_eligible_at);
        RETURN NEW;
    END IF;
    mutable_columns := ARRAY['state', 'reason', 'source_attempts', 'infrastructure_attempts',
        'retry_after', 'last_attempt_key', 'capture_key', 'capture_digest', 'capture_bytes', 'transport_receipt'];
    IF TG_TABLE_NAME = 'discovery_page' THEN
        mutable_columns := mutable_columns || ARRAY['claim_ordinal', 'claim_state', 'decoded_digest', 'cursor_initial',
            'cursor_committed', 'cursor_next', 'cursor_ordinal', 'complete', 'findings', 'acceptance_result_id'];
        IF NEW.claim_ordinal < OLD.claim_ordinal THEN
            RAISE EXCEPTION 'claim ordinal cannot decrease' USING ERRCODE = '23514';
        END IF;
        IF OLD.state IN ('accepted', 'failed') AND NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'terminal page cannot change' USING ERRCODE = '55000';
        END IF;
    ELSE
        mutable_columns := mutable_columns || ARRAY['next_eligible_at', 'eligibility_watermark', 'claimed_epoch', 'claimed_fence'];
        IF OLD.state IN ('verified', 'failed', 'exhausted', 'expired') AND NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'terminal request cannot change' USING ERRCODE = '55000';
        END IF;
        IF OLD.eligibility_watermark IS NOT NULL AND
           (NEW.eligibility_watermark IS NULL OR NEW.eligibility_watermark < OLD.eligibility_watermark
            OR NEW.next_eligible_at < OLD.eligibility_watermark) THEN
            RAISE EXCEPTION 'retry eligibility cannot decrease' USING ERRCODE = '23514';
        END IF;
        NEW.eligibility_watermark := GREATEST(NEW.eligibility_watermark, NEW.next_eligible_at);
    END IF;
    IF (to_jsonb(NEW) - mutable_columns) IS DISTINCT FROM (to_jsonb(OLD) - mutable_columns) THEN
        RAISE EXCEPTION 'request inputs are frozen' USING ERRCODE = '55000';
    END IF;
    IF NEW.source_attempts < OLD.source_attempts OR NEW.infrastructure_attempts < OLD.infrastructure_attempts
       OR (OLD.retry_after IS NOT NULL AND (NEW.retry_after IS NULL OR NEW.retry_after < OLD.retry_after)) THEN
        RAISE EXCEPTION 'retry accounting cannot decrease' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$request$;
-- +goose StatementEnd
