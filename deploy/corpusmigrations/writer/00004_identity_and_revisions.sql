-- These guards enforce same-schema parentage and the database country even for
-- direct inserts. No future conversion, part, build or release object is used.
-- +goose StatementBegin
CREATE FUNCTION silver.check_identity_country() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $guard$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM ingest.country_admission a
                   WHERE a.id = 1 AND a.country_code = split_part(NEW.identity_key, ':', 1)) THEN
        RAISE EXCEPTION 'identity country differs from writer' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$guard$;
CREATE FUNCTION silver.check_document_revision_key() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $guard$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM silver.document_identity d WHERE d.id = NEW.document_identity_id
                   AND d.identity_key = split_part(NEW.revision_key, ':rev:', 1)) THEN
        RAISE EXCEPTION 'revision key differs from identity' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$guard$;
CREATE FUNCTION silver.check_provision_revision_key() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $guard$
DECLARE parent silver.document_revision%ROWTYPE;
BEGIN
    SELECT * INTO parent FROM silver.document_revision d WHERE d.id = NEW.document_revision_id;
    IF parent.id IS NULL OR NEW.provision_key <> parent.revision_key || ':provision:' || NEW.local_key THEN
        RAISE EXCEPTION 'provision key differs from document revision' USING ERRCODE = '23514';
    END IF;
    IF NEW.continuity_assertion_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM silver.identity_assertion a WHERE a.id = NEW.continuity_assertion_id
          AND a.kind = 'continuity' AND a.review_state = 'confirmed'
          AND a.document_identity_id = parent.document_identity_id
    ) THEN
        RAISE EXCEPTION 'stable provision requires confirmed continuity' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$guard$;
-- Serializing the natural observed assertion makes minting atomic across concurrent
-- attempts. This VOLATILE function uses fresh statement snapshots
-- after the advisory lock; ON CONFLICT plus a single CTE snapshot cannot do that.
CREATE FUNCTION silver.mint_document_identity(p_key text, p_observation text, p_source text,
    p_external text, p_number text, p_type text, p_title text, p_execution text, p_evidence text, p_expires_at timestamptz)
RETURNS bigint LANGUAGE plpgsql VOLATILE SET search_path = pg_catalog AS $mint$
DECLARE identity_id bigint;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended(jsonb_build_array(
        p_observation, p_source, p_external, p_number, p_type, p_title)::text, 0));
    IF p_expires_at <= clock_timestamp() THEN
        RETURN NULL;
    END IF;
    SELECT min(a.document_identity_id) INTO identity_id FROM silver.identity_assertion a
    WHERE a.observation_key = p_observation AND a.source_id = p_source AND a.external_id = p_external
      AND a.normalized_number = p_number AND a.document_type = p_type AND a.title_hash = p_title
      AND a.kind = 'observed' HAVING count(DISTINCT a.document_identity_id) = 1;
    IF identity_id IS NULL AND EXISTS (SELECT 1 FROM silver.identity_assertion a
        WHERE a.observation_key = p_observation AND a.source_id = p_source AND a.external_id = p_external
          AND a.normalized_number = p_number AND a.document_type = p_type AND a.title_hash = p_title
          AND a.kind = 'observed') THEN
        RETURN NULL;
    END IF;
    IF identity_id IS NOT NULL THEN
        RETURN identity_id;
    END IF;
    INSERT INTO silver.document_identity (identity_key, entity_kind, created_by_execution_key)
    VALUES (p_key, 'document', p_execution) RETURNING id INTO identity_id;
    INSERT INTO silver.identity_assertion (document_identity_id, observation_key, source_id, external_id,
        normalized_number, document_type, title_hash, kind, review_state, evidence_hash, intake_execution_key)
    VALUES (identity_id, p_observation, p_source, p_external, p_number, p_type, p_title,
        'observed', 'unreviewed', p_evidence, p_execution);
    RETURN identity_id;
END
$mint$;
