CREATE TABLE silver.document_identity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_key text NOT NULL UNIQUE CHECK (identity_key ~ '^[a-z]{2}:doc:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
    entity_kind text NOT NULL CHECK (entity_kind IN ('document')),
    -- Cross-schema foreign keys are forbidden. Fenced queries resolve this key.
    created_by_execution_key text NOT NULL CHECK (created_by_execution_key ~ '^execution-[0-9a-f]{32}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX document_identity_execution_idx ON silver.document_identity (created_by_execution_key, id);

CREATE TABLE silver.identity_assertion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_identity_id bigint NOT NULL REFERENCES silver.document_identity (id),
    observation_key text NOT NULL CHECK (observation_key ~ '^observation-[0-9a-f]{32}$'),
    source_id text NOT NULL CHECK (source_id <> ''),
    external_id text NOT NULL CHECK (external_id <> ''),
    normalized_number text NOT NULL,
    document_type text NOT NULL,
    title_hash text NOT NULL CHECK (title_hash ~ '^[0-9a-f]{64}$'),
    kind text NOT NULL CHECK (kind IN ('observed', 'merge', 'split', 'continuity')),
    related_identity_id bigint REFERENCES silver.document_identity (id),
    review_state text NOT NULL CHECK (review_state IN ('unreviewed', 'confirmed', 'rejected', 'unresolved')),
    evidence_hash text NOT NULL CHECK (evidence_hash ~ '^[0-9a-f]{64}$'),
    intake_execution_key text NOT NULL CHECK (intake_execution_key ~ '^execution-[0-9a-f]{32}$'),
    CONSTRAINT identity_assertion_natural_key UNIQUE NULLS NOT DISTINCT
        (observation_key, source_id, external_id, normalized_number, document_type, title_hash, kind, document_identity_id, related_identity_id, evidence_hash, review_state),
    CHECK ((kind IN ('merge', 'split')) = (related_identity_id IS NOT NULL)),
    CHECK (related_identity_id IS NULL OR related_identity_id <> document_identity_id)
);
CREATE INDEX identity_assertion_identity_idx ON silver.identity_assertion (document_identity_id, id);
CREATE INDEX identity_assertion_source_idx ON silver.identity_assertion (source_id, external_id, id);
CREATE INDEX identity_assertion_related_idx ON silver.identity_assertion (related_identity_id, id);
CREATE INDEX identity_assertion_title_idx ON silver.identity_assertion (title_hash, id);
CREATE INDEX identity_assertion_evidence_idx ON silver.identity_assertion (evidence_hash, id);
CREATE INDEX identity_assertion_execution_idx ON silver.identity_assertion (intake_execution_key, id);

