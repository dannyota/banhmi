func TestExtensionOwnerGuard(t *testing.T) {
	t.Run("migration-owned-member", func(t *testing.T) {
		f := newFixture(t, "control")
		// Bootstrap grants this login database and public-schema CREATE.
		// A trusted extension lets the login own the extension itself.
		execSQL(t, f.db, "CREATE EXTENSION btree_gist WITH SCHEMA public VERSION '1.7'; CREATE FUNCTION public.foreign_object() RETURNS integer LANGUAGE sql AS 'SELECT 1'; ALTER EXTENSION btree_gist ADD FUNCTION public.foreign_object()")
		var migrationOwned bool
		if err := f.db.QueryRow(`SELECT e.extowner=r.oid AND NOT r.rolsuper
            FROM pg_extension e JOIN pg_roles r ON r.rolname=current_user
            WHERE e.extname='btree_gist'`).Scan(&migrationOwned); err != nil || !migrationOwned {
			t.Fatalf("fixture extension must belong to the non-superuser migration login: %v", err)
		}
		// Exercise the catalog predicate separately from the early global guard.
		rows, err := f.db.Query(catalogObjects, f.chain.table)
		if err != nil {
			t.Fatal(err)
		}
		found := false
		for rows.Next() {
			var schema, kind, identity, owner, parent, cs, cr string
			var extension, versionObject, internal bool
			if err := rows.Scan(&schema, &kind, &identity, &owner, &extension, &versionObject, &parent, &internal, &cs, &cr); err != nil {
				_ = rows.Close()
				t.Fatal(err)
			}
			if schema == "public" && kind == "function" && identity == "foreign_object()" {
				found = true
				if extension {
					_ = rows.Close()
					t.Fatal("migration-owned extension sheltered a foreign function")
				}
			}
		}
		if err := rows.Err(); err != nil {
			_ = rows.Close()
			t.Fatal(err)
		}
		if err := rows.Close(); err != nil {
			t.Fatal(err)
		}
		if !found {
			t.Fatal("catalog omitted the foreign function")
		}
		snapshot := func() string {
			var extensions, members string
			if err := f.admin.QueryRow(`SELECT COALESCE(json_agg(e ORDER BY e.extname)::text,'[]')
                FROM pg_extension e`).Scan(&extensions); err != nil {
				t.Fatal(err)
			}
			if err := f.admin.QueryRow(`SELECT COALESCE(json_agg(d ORDER BY d.refobjid,d.classid,d.objid,d.objsubid)::text,'[]')
                FROM pg_depend d WHERE d.refclassid='pg_extension'::regclass AND d.deptype='e'`).Scan(&members); err != nil {
				t.Fatal(err)
			}
			return catalogSnapshot(t, f) + extensions + members
		}
		before := snapshot()
		for _, status := range []bool{false, true} {
			err := migrate(context.Background(), f.db, f.chain, options{status: status}, io.Discard)
			if err == nil || !strings.HasPrefix(err.Error(), "preflight:") || !strings.Contains(err.Error(), "extension must be owned by a superuser: btree_gist") {
				t.Fatalf("extension owner guard must reject before Goose, status=%t: %v", status, err)
			}
			if got := snapshot(); got != before {
				t.Fatal("extension owner rejection changed catalog or version history")
			}
		}
		rejectFixture(t, f, f.chain)
	})
	for _, name := range []string{"writer", "release"} {
		t.Run(name+"-administrator-owned", func(t *testing.T) {
			f := newFixture(t, name)
			var count int
			var superuserOwned bool
			if err := f.db.QueryRow(`SELECT count(*), COALESCE(bool_and(r.rolsuper),false)
                FROM pg_extension e JOIN pg_roles r ON r.oid=e.extowner
                WHERE e.extname IN ('vector','btree_gist','plpgsql')`).Scan(&count, &superuserOwned); err != nil {
				t.Fatal(err)
			}
			if count != 3 || !superuserOwned {
				t.Fatal("administrator-installed extensions must all be owned by a superuser")
			}
			assertInventory(t, f, 0)
			assertReadOnlyStatus(t, f, false)
			applyFixture(t, f, options{})
			assertInventory(t, f, finalVersion(f.chain))
			assertReadOnlyStatus(t, f, true)
		})
	}
}

