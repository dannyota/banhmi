func testDifferentChainLock(t *testing.T) {
	f := newFixture(t, "writer")
	holder, err := f.db.Conn(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = holder.Close() }()
	if _, err := holder.ExecContext(context.Background(), "SELECT pg_advisory_lock(1129271888,1)"); err != nil {
		t.Fatal(err)
	}
	defer func() { _, _ = holder.ExecContext(context.Background(), "SELECT pg_advisory_unlock(1129271888,1)") }()
	control, err := loadChain("control")
	if err != nil {
		t.Fatal(err)
	}
	// A second pool prevents session-level reentrancy from hiding a leaked lock.
	other := openTestDB(t, f.migrationURL)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	beforeCancellation := catalogSnapshot(t, f)
	canceledCtx, stop := context.WithTimeout(context.Background(), 100*time.Millisecond)
	err = migrate(canceledCtx, other, control, options{}, io.Discard)
	stop()
	if err == nil || !strings.Contains(err.Error(), "acquire migration lock") {
		t.Fatalf("canceled lock wait must fail: %v", err)
	}
	if got := catalogSnapshot(t, f); got != beforeCancellation {
		t.Fatal("canceled lock wait changed catalog")
	}
	finished := make(chan error, 1)
	go func() { finished <- migrate(ctx, other, control, options{}, io.Discard) }()
	// Poll the server's actual wait event, with a deadline, instead of assuming
	// a scheduler delay means that the competing command holds the lock.
	deadline := time.Now().Add(5 * time.Second)
	for {
		var waiting bool
		if err := f.admin.QueryRow(`SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE datname=$1 AND wait_event='advisory')`, f.database).Scan(&waiting); err != nil {
			t.Fatal(err)
		}
		if waiting {
			break
		}
		select {
		case err := <-finished:
			t.Fatalf("other chain did not wait for lock: %v", err)
		default:
		}
		if time.Now().After(deadline) {
			t.Fatal("other chain never reached advisory wait")
		}
		time.Sleep(10 * time.Millisecond)
	}
	before := catalogSnapshot(t, f)
	// Apply the writer prefix with the holder session while the other chain
	// waits. Applying SQL directly avoids taking the same advisory lock twice.
	data, err := corpusmigrationsSQL("writer")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := holder.ExecContext(context.Background(), data); err != nil {
		t.Fatal(err)
	}
	makeVersionTable(t, f, appliedHistory(f.chain, f.chain.versions[0]))
	if catalogSnapshot(t, f) == before {
		t.Fatal("writer initialization did not change fixture")
	}
	if _, err := holder.ExecContext(context.Background(), "SELECT pg_advisory_unlock(1129271888,1)"); err != nil {
		t.Fatal(err)
	}
	select {
	case err := <-finished:
		if err == nil || !strings.HasPrefix(err.Error(), "preflight:") {
			t.Fatalf("wrong chain must reject after waiting: %v", err)
		}
	case <-ctx.Done():
		t.Fatal("other chain did not finish after unlock")
	}
	assertInventory(t, f, f.chain.versions[0])
}

func TestReadOnlyStatus(t *testing.T) {
	for _, name := range []string{"writer", "release", "control"} {
		for _, applied := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s-applied-%t", name, applied), func(t *testing.T) {
				f := newFixture(t, name)
				if applied {
					applyFixture(t, f, options{})
					execSQL(t, f.db, "GRANT SELECT ON public."+f.chain.table+" TO banhmi_corpus_"+name+"_app")
				}
				u, err := url.Parse(f.migrationURL)
				if err != nil {
					t.Fatal(err)
				}
				u.User = url.User("banhmi_corpus_" + name + "_app")
				readonly := openTestDB(t, readOnlyFixtureURL(*u))
				before := catalogSnapshot(t, f)
				var out bytes.Buffer
				if err := migrate(context.Background(), readonly, f.chain, options{status: true}, &out); err != nil {
					t.Fatal(err)
				}
				state := "pending"
				if applied {
					state = "applied"
				}
				for _, file := range f.chain.files {
					if !strings.Contains(out.String(), file+" "+state) {
						t.Fatal("status omitted file or state")
					}
				}
				if got := catalogSnapshot(t, f); got != before {
					t.Fatal("read-only status changed catalog/history")
				}
				if applied {
					execSQL(t, f.db, "REVOKE SELECT ON public."+f.chain.table+" FROM banhmi_corpus_"+name+"_app")
					before = catalogSnapshot(t, f)
					if err := migrate(context.Background(), readonly, f.chain, options{status: true}, io.Discard); err == nil || !strings.HasPrefix(err.Error(), "preflight:") {
						t.Fatalf("status must fail closed on missing SELECT: %v", err)
					}
					if got := catalogSnapshot(t, f); got != before {
						t.Fatal("status permission failure changed catalog/history")
					}
				}
				if !applied {
					// Empty and zero-only selected version tables are valid too.
					makeVersionTable(t, f, "(0,true)")
					execSQL(t, f.db, "GRANT SELECT ON public."+f.chain.table+" TO banhmi_corpus_"+name+"_app")
					for _, empty := range []bool{false, true} {
						if empty {
							execSQL(t, f.db, "DELETE FROM public."+f.chain.table)
						}
						before = catalogSnapshot(t, f)
						if err := migrate(context.Background(), readonly, f.chain, options{status: true}, io.Discard); err != nil {
							t.Fatal(err)
						}
						if got := catalogSnapshot(t, f); got != before {
							t.Fatal("status initialized existing version table")
						}
					}
				}
			})
		}
	}
}

// The lock and extension fixtures deliberately apply only the first prefix.
// No test-only migration is embedded.
func corpusmigrationsSQL(name string) (string, error) {
	c, err := loadChain(name)
	if err != nil {
		return "", err
	}
	data, err := corpusmigrations.FS.ReadFile(name + "/" + c.files[0])
	if err != nil {
		return "", err
	}
	up, _, _ := strings.Cut(string(data), "-- +goose Down")
	return up, nil
}

func testBootstrapGuards(t *testing.T) {
	for _, name := range []string{"writer", "release", "control"} {
		t.Run(name, func(t *testing.T) {
			f := newFixture(t, name)
			base := []string{"--no-psqlrc", "--dbname", f.adminURL, "--set", "ON_ERROR_STOP=1"}
			variables := []string{"migration_login_role=banhmi_corpus_" + name + "_migrator", "runtime_login_role=banhmi_corpus_" + name + "_app"}
			if name == "writer" {
				variables = append(variables, "export_login_role=banhmi_corpus_writer_exporter")
			}
			if name == "release" {
				variables = append(variables, "loader_login_role=banhmi_corpus_release_load")
			}
			file := filepath.Join("..", "..", "deploy", "corpusmigrations", "bootstrap", name+".sql")
			for omit := range variables {
				args := append([]string{}, base...)
				for i, value := range variables {
					if i != omit {
						args = append(args, "--set", value)
					}
				}
				args = append(args, "--file", file)
				before := catalogSnapshot(t, f)
				if output, err := exec.Command("psql", args...).CombinedOutput(); err == nil {
					t.Fatalf("bootstrap accepted missing %s: %s", variables[omit], output)
				}
				if got := catalogSnapshot(t, f); got != before {
					t.Fatal("incomplete bootstrap created objects")
				}
			}
			if name == "release" {
				args := append([]string{}, base...)
				for _, value := range variables {
					args = append(args, "--set", value)
				}
				args = append(args, "--set", "restore_login_role=banhmi_corpus_release_restore", "--file", file)
				if output, err := exec.Command("psql", args...).CombinedOutput(); err == nil {
					t.Fatalf("bootstrap accepted loader plus restore: %s", output)
				}
				// The restore branch belongs to bootstrap even before evidence
				// tables exist. Sealing/grant recovery is a later projection test.
				args = append([]string{}, base...)
				for _, value := range variables[:2] {
					args = append(args, "--set", value)
				}
				args = append(args, "--set", "restore_login_role=banhmi_corpus_release_restore", "--file", file)
				t.Cleanup(func() {
					execSQL(t, f.admin, "REVOKE banhmi_corpus_release_migrator FROM banhmi_corpus_release_restore; REVOKE CONNECT ON DATABASE "+f.database+" FROM banhmi_corpus_release_restore")
				})
				// Switching modes requires explicitly closing the former loader access.
				execSQL(t, f.admin, "REVOKE CONNECT ON DATABASE "+f.database+" FROM banhmi_corpus_release_load")
				tool(t, "psql", args...)
				var valid bool
				if err := f.admin.QueryRow(`SELECT EXISTS(SELECT 1 FROM pg_auth_members m JOIN pg_roles member ON member.oid=m.member
                    JOIN pg_roles parent ON parent.oid=m.roleid WHERE member.rolname='banhmi_corpus_release_restore'
                    AND parent.rolname='banhmi_corpus_release_migrator' AND NOT m.inherit_option AND m.set_option AND NOT m.admin_option)
                    AND NOT has_database_privilege('banhmi_corpus_release_restore',current_database(),'CREATE')`).Scan(&valid); err != nil || !valid {
					t.Fatalf("invalid temporary restore binding: %v", err)
				}
			}
			var publicConnect, runtimeCreate, migrationSuper bool
			if err := f.admin.QueryRow(`SELECT EXISTS(SELECT 1 FROM pg_database d CROSS JOIN LATERAL aclexplode(d.datacl) a
                WHERE d.datname=current_database() AND a.grantee=0 AND a.privilege_type='CONNECT'),
                has_database_privilege($1,current_database(),'CREATE') OR has_schema_privilege($1,'public','CREATE'),
                (SELECT rolsuper FROM pg_roles WHERE rolname=$2)`, "banhmi_corpus_"+name+"_app", "banhmi_corpus_"+name+"_migrator").Scan(&publicConnect, &runtimeCreate, &migrationSuper); err != nil {
				t.Fatal(err)
			}
			if publicConnect || runtimeCreate || migrationSuper {
				t.Fatal("bootstrap grants exceed the role matrix")
			}
		})
	}
}
