func rejectFixture(t *testing.T, f *chainFixture, selected chainSpec) {
	t.Helper()
	before := catalogSnapshot(t, f)
	for _, status := range []bool{false, true} {
		err := migrate(context.Background(), f.db, selected, options{status: status}, io.Discard)
		if err == nil || !strings.HasPrefix(err.Error(), "preflight:") {
			t.Fatalf("guard must reject before Goose, status=%t: %v", status, err)
		}
		if got := catalogSnapshot(t, f); got != before {
			t.Fatal("rejection changed catalog or version history")
		}
	}
	// The pinned lock must be released on every rejection path.
	other := openTestDB(t, f.migrationURL)
	conn, err := other.Conn(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = conn.Close() }()
	var acquired, released bool
	if err := conn.QueryRowContext(context.Background(), "SELECT pg_try_advisory_lock(1129271888,1)").Scan(&acquired); err != nil || !acquired {
		t.Fatalf("rejected migration leaked lock: %v", err)
	}
	if err := conn.QueryRowContext(context.Background(), "SELECT pg_advisory_unlock(1129271888,1)").Scan(&released); err != nil || !released {
		t.Fatalf("release fixture lock: %v", err)
	}
}

